// Builds the SQL that loads tiers, seats, and performances into the database
// from the config files. Safe to run again: existing rows are updated, and
// seat statuses (sales, holds) are never reset.
import type { Performance, Pricing, Seat } from "./types";
import { tierFor } from "./tiers";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (items: string[]) => `array[${items.map(q).join(", ")}]::text[]`;

export function buildSeedSql(seats: Seat[], pricing: Pricing, performances: Performance[]): string {
  const tiers = pricing.tiers
    .map((t, i) => `  (${q(t.id)}, ${q(t.name)}, ${t.priceCents}, ${i})`)
    .join(",\n");
  const seatRows = seats
    .map(
      (s) =>
        `  (${q(s.id)}, ${q(s.section)}, ${q(s.zone)}, ${q(s.row)}, ${s.number}, ${q(tierFor(s, pricing).id)}, ${s.accessible})`,
    )
    .join(",\n");
  const perfRows = performances
    .map(
      (p, i) =>
        `  (${q(p.id)}, ${q(p.label)}, ${p.startsAt ? `${q(p.startsAt)}::timestamptz` : "null"}, ${arr(p.grades)}, ${p.onSale}, ${i})`,
    )
    .join(",\n");

  return `-- Generated by \`npm run db:seed\` from config/ and data/seats.json. Do not edit by hand.
begin;

insert into tiers (id, name, price_cents, sort) values
${tiers}
on conflict (id) do update set name = excluded.name, price_cents = excluded.price_cents, sort = excluded.sort;

insert into seats (id, section, zone, row, number, tier_id, accessible) values
${seatRows}
on conflict (id) do update set section = excluded.section, zone = excluded.zone, row = excluded.row,
  number = excluded.number, tier_id = excluded.tier_id, accessible = excluded.accessible;

insert into performances (id, label, starts_at, grades, on_sale, sort) values
${perfRows}
on conflict (id) do update set label = excluded.label, starts_at = excluded.starts_at,
  grades = excluded.grades, on_sale = excluded.on_sale, sort = excluded.sort;

-- Every seat starts out available for every night.
insert into performance_seats (performance_id, seat_id)
select p.id, s.id from performances p cross join seats s
on conflict do nothing;

commit;
`;
}
